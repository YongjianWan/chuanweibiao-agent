const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const legacyLocatedPath = path.join(root, "data", "interim", "located.json");
const legacySectionsPath = path.join(root, "data", "interim", "sections.json");
const projectDir = path.join(root, "data", "projects", "jiyang-epc");
const seedPath = path.join(root, "prototype", "js", "located-seed.js");
const mockDataPath = path.join(root, "prototype", "js", "mock-data.js");
const realReviewsInputPath = path.join(projectDir, "reviews", "reviews.json");
const officialReportInputPath = path.join(root, "data", "out", "report", "report.json");
const realResultsPath = path.join(root, "prototype", "js", "real-results.js");
const LOW_CONFIDENCE_THRESHOLD = 0.85;

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function exists(filePath) {
  return fs.existsSync(filePath);
}

function compactText(value, maxLength = 360) {
  const text = String(value || "").replace(/\s+/g, " ").trim();
  return text.length > maxLength ? text.slice(0, maxLength - 1) + "…" : text;
}

function sectionMap(sectionsPath) {
  if (!exists(sectionsPath)) return new Map();
  const sections = readJson(sectionsPath);
  const sectionById = new Map(sections.map((section) => [section.id, section]));
  return sectionById;
}

function seedPackage(packageRow, sectionById, fallbackBidder = null) {
  const base = packageRow.item_id ? {
    item_id: packageRow.item_id,
    item_guid: packageRow.item_guid || null,
    bidder: packageRow.bidder || fallbackBidder
  } : {};

  return {
    ...base,
      name: packageRow.name,
      pool_sections: packageRow.pool_sections,
      candidates: packageRow.candidates,
      units: packageRow.units,
      fallback: Boolean(packageRow.fallback),
      evidence_chars: packageRow.evidence_chars,
      budget: packageRow.budget,
      picked: packageRow.picked.slice(0, 4).map((pickedRow) => {
        const section = sectionById.get(pickedRow.section_id) || {};
        return {
          section_id: pickedRow.section_id,
          file: pickedRow.file,
          item_id: pickedRow.item_id || packageRow.item_id || null,
          item_guid: pickedRow.item_guid || packageRow.item_guid || null,
          bidder: pickedRow.bidder || packageRow.bidder || fallbackBidder,
          path: pickedRow.path,
          unit: pickedRow.unit,
          match_score: pickedRow.match_score,
          hit: pickedRow.hit,
          chars: pickedRow.chars,
          truncated: Boolean(pickedRow.truncated),
          page: pickedRow.page || section.page || null,
          level: section.level || (Array.isArray(pickedRow.path) ? pickedRow.path.length : null),
          text: compactText(section.text)
        };
      })
  };
}

function buildProjectLocatedSeed() {
  const evidenceDir = path.join(projectDir, "evidence");
  if (!exists(evidenceDir)) return null;

  const bidders = fs.readdirSync(evidenceDir)
    .filter((name) => exists(path.join(evidenceDir, name, "located.json")))
    .sort();
  const seed = [];
  bidders.forEach((bidder) => {
    const located = readJson(path.join(evidenceDir, bidder, "located.json"));
    const sections = sectionMap(path.join(projectDir, "sections", bidder, "sections.json"));
    located
      .filter((packageRow) => Array.isArray(packageRow.picked) && packageRow.picked.length)
      .forEach((packageRow) => seed.push(seedPackage(packageRow, sections, bidder)));
  });

  if (!seed.length) return null;
  return {
    seed,
    sourceLocated: "data/projects/jiyang-epc/evidence/*/located.json",
    sourceSections: "data/projects/jiyang-epc/sections/*/sections.json"
  };
}

function buildLegacyLocatedSeed() {
  const located = readJson(legacyLocatedPath);
  const sections = sectionMap(legacySectionsPath);
  return {
    seed: located
      .filter((packageRow) => Array.isArray(packageRow.picked) && packageRow.picked.length)
      .slice(0, 19)
      .map((packageRow) => seedPackage(packageRow, sections)),
    sourceLocated: "data/interim/located.json",
    sourceSections: "data/interim/sections.json"
  };
}

function buildLocatedSeed() {
  return buildProjectLocatedSeed() || buildLegacyLocatedSeed();
}

function writeLocatedSeed(seed, sourceLocated) {
  const body = [
    `// Generated by scripts/build-prototype-mock.js from ${sourceLocated}. Do not edit by hand.`,
    "window.LOCATED_SEED = " + JSON.stringify(seed, null, 2) + ";",
    ""
  ].join("\n");
  fs.writeFileSync(seedPath, body, "utf8");
}

function loadPrototypeData(seed) {
  const context = {
    window: {
      LOCATED_SEED: seed
    }
  };
  vm.runInNewContext(fs.readFileSync(mockDataPath, "utf8"), context, { filename: mockDataPath });
  return context.window.PROTOTYPE_DATA;
}

function round1(value) {
  return Math.round(Number(value || 0) * 10) / 10;
}

function orderedBidderNames(data, reviewResults) {
  const seen = new Set();
  const resultNames = new Set(reviewResults.map((row) => row.bidder).filter(Boolean));
  const ordered = [];
  data.bidders.forEach((bidder) => {
    if (resultNames.has(bidder.name) && !seen.has(bidder.name)) {
      ordered.push(bidder.name);
      seen.add(bidder.name);
    }
  });
  [...resultNames].sort().forEach((name) => {
    if (!seen.has(name)) {
      ordered.push(name);
      seen.add(name);
    }
  });
  return ordered;
}

function normalizeRealResults(rawResults, data) {
  const bidderByName = new Map(data.bidders.map((bidder) => [bidder.name, bidder]));
  return rawResults.map((row) => {
    const bidder = bidderByName.get(row.bidder);
    return {
      ...row,
      bidder_id: row.bidder_id || (bidder ? bidder.id : row.bidder),
      cite: Array.isArray(row.cite) ? row.cite : [],
      miss_reason: row.miss_reason || null,
      last_error: row.last_error || "",
      perf: row.perf && typeof row.perf === "object" ? row.perf : {
        in_tokens: 0,
        out_tokens: 0,
        latency_ms: 0
      }
    };
  });
}

function flagWhy(row) {
  if (row.miss_reason === "not_found") return "证据定位未命中，检索未命中不等于投标人未写";
  if ((row.attempts || 0) > 1) return `经 ${row.attempts} 次尝试才成功（重试过）`;
  return "置信度低于阈值（证据降级或截断，见对应证据包）";
}

function buildAuditRows(data, bidderNames, resultsByKey) {
  return data.scoringTable.items.flatMap((item) => {
    const rows = bidderNames.map((bidder) => resultsByKey.get(bidder + "__" + item.id));
    if (rows.some((row) => !row || row.status !== "rated")) return [];

    const groups = new Set();
    const tierDist = item.tiers.reduce((dist, tier) => {
      dist[tier.tier] = 0;
      return dist;
    }, {});
    let misses = 0;
    rows.forEach((row) => {
      if (row.tier == null) {
        groups.add("未命中");
        misses += 1;
        return;
      }
      groups.add(row.tier);
      tierDist[row.tier] = (tierDist[row.tier] || 0) + 1;
    });
    if (groups.size !== 1) return [];

    if (misses) {
      tierDist["未命中"] = misses;
      return [{
        item_id: item.id,
        kind: "no_discrimination",
        detail: bidderNames.length + " 家全部 0 分（未命中）",
        tier_dist: tierDist
      }];
    }
    const only = [...groups][0];
    return [{
      item_id: item.id,
      kind: "no_discrimination",
      detail: bidderNames.length + " 家全部判「" + only + "」档",
      tier_dist: tierDist
    }];
  });
}

function buildRealReportData(realJson, reviewResults, data) {
  const bidderNames = orderedBidderNames(data, reviewResults);
  const resultsByKey = new Map(reviewResults.map((row) => [row.bidder + "__" + row.item_id, row]));
  const matrix = data.scoringTable.items.map((item) => {
    const scores = {};
    bidderNames.forEach((bidder) => {
      const row = resultsByKey.get(bidder + "__" + item.id);
      scores[bidder] = row && row.status === "rated" ? row.score : null;
    });
    return {
      item_id: item.id,
      name: item.name,
      max_score: item.max_score,
      scores
    };
  });
  const totals = {};
  bidderNames.forEach((bidder) => {
    const rows = data.scoringTable.items.map((item) => resultsByKey.get(bidder + "__" + item.id));
    const score = rows.reduce((sum, row) => sum + (row && typeof row.score === "number" ? row.score : 0), 0);
    totals[bidder] = {
      score: round1(score),
      unrated: rows.filter((row) => !row || row.status !== "rated").length,
      expert_score: round1(score),
      expert_overrides: 0
    };
  });
  const sumAttempts = reviewResults.reduce((sum, row) => sum + (row.attempts || 0), 0);
  const firstCalls = reviewResults.filter((row) => (row.attempts || 0) >= 1).length;
  const latencySec = round1(reviewResults.reduce((sum, row) => sum + ((row.perf || {}).latency_ms || 0), 0) / 1000);

  return {
    project: realJson.project || data.reportData.project,
    generated_at: realJson.generated_at || new Date().toISOString(),
    bidders: bidderNames,
    matrix,
    totals,
    details: reviewResults,
    unrated: reviewResults
      .filter((row) => row.status === "unrated")
      .map((row) => ({
        bidder: row.bidder,
        item_id: row.item_id,
        attempts: row.attempts || 0,
        last_error: row.last_error || ""
      })),
    review_flags: reviewResults
      .filter((row) => row.status === "rated" && (row.confidence || 0) < LOW_CONFIDENCE_THRESHOLD)
      .map((row) => ({
        bidder: row.bidder,
        item_id: row.item_id,
        confidence: row.confidence,
        why: flagWhy(row)
      })),
    audit: buildAuditRows(data, bidderNames, resultsByKey),
    expert_reviews: [],
    perf: {
      wall_clock_sec: typeof (realJson.perf || {}).wall_clock_sec === "number" ? realJson.perf.wall_clock_sec : null,
      wall_clock_note: "未采集（逐项 latency 之和为 " + latencySec + " 秒，并发下实际墙钟低于该值）",
      concurrency: (realJson.perf || {}).concurrency || "未采集",
      calls: bidderNames.length * data.scoringTable.items.length,
      retries: sumAttempts - firstCalls,
      in_tokens: reviewResults.reduce((sum, row) => sum + ((row.perf || {}).in_tokens || 0), 0),
      out_tokens: reviewResults.reduce((sum, row) => sum + ((row.perf || {}).out_tokens || 0), 0),
      gpu: "未采集",
      vram_peak_gb: null,
      gpu_note: "模型为远程托管端点时，我方进程内无法采集显存；此处显示为未采集。"
    },
    compute_notes: data.reportData.compute_notes
  };
}

function buildRealRunEvents(reviewResults, data) {
  const byKey = new Map(reviewResults.map((row) => [row.bidder_id + "__" + row.item_id, row]));
  const events = [
    { type: "stage", stage: "PDF 入库", status: "running", message: "开始读取 12 家投标技术标 PDF" },
    { type: "stage", stage: "PDF 入库", status: "done", message: "完成 12 家投标文件入库" },
    { type: "stage", stage: "证据定位", status: "running", message: "按评分项绑定关系进入单 PDF 内部定位证据" },
    { type: "stage", stage: "证据定位", status: "done", message: "真实证据包已生成，开始逐项评审" },
    { type: "stage", stage: "逐项评审", status: "running", message: "逐项评审开始" }
  ];
  data.bidders.forEach((bidder) => {
    data.scoringTable.items.forEach((item) => {
      const row = byKey.get(bidder.id + "__" + item.id);
      if (!row) return;
      for (let attempt = 1; attempt < (row.attempts || 1); attempt += 1) {
        events.push({
          type: "retry",
          bidder_id: row.bidder_id,
          item_id: row.item_id,
          attempt,
          max_attempts: row.attempts,
          message: "模型返回格式不完整，准备重试"
        });
      }
      events.push({
        type: "review",
        bidder_id: row.bidder_id,
        item_id: row.item_id,
        status: row.status,
        score: row.score,
        tier: row.tier,
        miss_reason: row.miss_reason,
        confidence: row.confidence,
        attempts: row.attempts,
        last_error: row.last_error,
        in_tokens: (row.perf || {}).in_tokens || 0,
        out_tokens: (row.perf || {}).out_tokens || 0,
        latency_ms: (row.perf || {}).latency_ms || 0
      });
    });
  });
  events.push({ type: "stage", stage: "结果汇总", status: "running", message: "生成并排结果矩阵和复核清单" });
  events.push({ type: "stage", stage: "结果汇总", status: "done", message: "真实评审结果已汇总完成" });
  return events;
}

function writeRealResults(data) {
  const hasOfficialReport = exists(officialReportInputPath);
  const hasRealReviews = exists(realReviewsInputPath);
  if (!hasOfficialReport && !hasRealReviews) {
    fs.writeFileSync(realResultsPath, [
      "// Generated by scripts/build-prototype-mock.js. No real reviews found; mock data remains active.",
      "window.REAL_RESULTS = null;",
      ""
    ].join("\n"), "utf8");
    return { count: 0 };
  }

  const officialReport = hasOfficialReport ? readJson(officialReportInputPath) : null;
  const realJson = hasRealReviews ? readJson(realReviewsInputPath) : { review_results: [] };
  const rawResults = Array.isArray(realJson.review_results) ? realJson.review_results : [];
  const reportDetails = officialReport && Array.isArray(officialReport.details) ? officialReport.details : [];
  const sourceResults = reportDetails.length ? reportDetails : rawResults;
  const reviewResults = normalizeRealResults(sourceResults, data);
  const realData = {
    source_reviews_json: hasRealReviews ? "data/projects/jiyang-epc/reviews/reviews.json" : "",
    source_report_json: hasOfficialReport ? "data/out/report/report.json" : "",
    generated_by: "scripts/build-prototype-mock.js",
    generated_at: officialReport && officialReport.generated_at ? officialReport.generated_at : new Date().toISOString(),
    model: realJson.model || "",
    reviewResults,
    reportData: officialReport || buildRealReportData(realJson, reviewResults, data),
    runEvents: buildRealRunEvents(reviewResults, data)
  };
  fs.writeFileSync(realResultsPath, [
    "// Generated by scripts/build-prototype-mock.js from " +
      (hasOfficialReport ? "data/out/report/report.json" : "data/projects/jiyang-epc/reviews/reviews.json") +
      ". Do not edit by hand.",
    "window.REAL_RESULTS = " + JSON.stringify(realData, null, 2) + ";",
    ""
  ].join("\n"), "utf8");
  return { count: reviewResults.length };
}

